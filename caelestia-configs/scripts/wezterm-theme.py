#!/usr/bin/env python3
"""Generate WezTerm theme.lua from Caelestia scheme.json.

Reads ~/.local/state/caelestia/scheme.json and writes
~/.config/wezterm/wezterm/theme.lua with full M3 palette integration.
"""

import json
import os
import sys
from pathlib import Path

SCHEME_PATH = Path.home() / ".local/state/caelestia/scheme.json"
THEME_PATH = Path.home() / ".config/wezterm/wezterm/theme.lua"


def hex_color(raw: str) -> str:
    """Ensure color is #rrggbb format."""
    raw = raw.strip().lstrip("#")
    if len(raw) == 6:
        return f"#{raw}"
    if len(raw) == 8:
        return f"#{raw[:6]}"
    return f"#{raw}"


def build_theme(colours: dict, mode: str) -> dict:
    """Map scheme.json colours to WezTerm theme structure."""
    is_dark = mode == "dark"

    # Terminal ANSI colors (term0..term15)
    ansi = [hex_color(colours.get(f"term{i}", "#000000")) for i in range(8)]
    brights = [hex_color(colours.get(f"term{i}", "#ffffff")) for i in range(8, 16)]

    # Tab bar: contrast flips with light/dark
    if is_dark:
        tab_bg = hex_color(colours.get("surfaceContainerLowest", "#000000"))
        tab_fg = hex_color(colours.get("onSurface", "#ffffff"))
        tab_active_fg = hex_color(colours.get("onPrimary", "#ffffff"))
    else:
        tab_bg = hex_color(colours.get("surfaceContainerHighest", "#e0e0e0"))
        tab_fg = hex_color(colours.get("surface", "#1c1c1c"))
        tab_active_fg = hex_color(colours.get("onPrimary", "#ffffff"))

    # Extended tab-bar colors for tab-title.lua custom rendering.
    # default_*  = inactive tab (blends into bar)
    # hover_*    = hovered non-active tab
    # active_*2  = active tab body/text (accent pop)
    # unseen     = unseen-output badge
    # progress_* = progress indicators
    hover_bg = hex_color(colours.get("secondary", "#888888"))
    active_bg2 = hex_color(colours.get("tertiary", tab_fg))
    active_fg2 = tab_bg  # inverse of active_bg2 for contrast

    return {
        "custom_colors": {
            "red": hex_color(colours.get("tertiary", "#ff4444")),
            "cyan": hex_color(colours.get("secondary", "#44ffff")),
            "magenta": hex_color(colours.get("primary", "#ff44ff")),
            "yellow": hex_color(colours.get("tertiaryContainer", "#ffff44")),
            "green": hex_color(colours.get("success", "#44ff44")),
        },
        "status": {
            "workspace": hex_color(colours.get("onSurfaceVariant", "#cccccc")),
            "mode": hex_color(colours.get("secondary", "#88ccff")),
            "leader": hex_color(colours.get("primary", "#ff88cc")),
            "leader_fg": hex_color(colours.get("onPrimary", "#ffffff")),
            "cwd": hex_color(colours.get("outline", "#999999")),
            "process": hex_color(colours.get("onSurfaceVariant", "#cccccc")),
            "clock": hex_color(colours.get("secondary", "#88ccff")),
            "battery": hex_color(colours.get("success", "#44ff44")),
        },
        "tab_bar": {
            "bg": tab_bg,
            "fg": tab_fg,
            "gray": hex_color(colours.get("outline", "#777777")),
            "active_bg": hex_color(colours.get("primary", "#ff88cc")),
            "active_fg": tab_active_fg,
            # Extended tab-bar colors (tab-title.lua / new-tab-button.lua)
            "default_bg": tab_bg,
            "default_fg": tab_fg,
            "hover_bg": hover_bg,
            "hover_fg": tab_fg,
            "active_bg2": active_bg2,
            "active_fg2": active_fg2,
            "unseen": hex_color(colours.get("error", "#ff4444")),
            "progress_ok": hex_color(colours.get("success", "#44ff44")),
            "progress_err": hex_color(colours.get("error", "#ff4444")),
            "progress_ind": tab_fg,
        },
        "terminal": {
            "ansi": ansi,
            "brights": brights,
            "background": hex_color(colours.get("background", "#1c1c1c")),
            "foreground": hex_color(colours.get("onBackground", "#e0e0e0")),
            "cursor_bg": hex_color(colours.get("primary", "#ff88cc")),
            "cursor_fg": hex_color(colours.get("onPrimary", "#ffffff")),
            "cursor_border": hex_color(colours.get("primary", "#ff88cc")),
            "selection_bg": hex_color(colours.get("primaryContainer", "#664455")),
            "selection_fg": hex_color(colours.get("onPrimaryContainer", "#ffffff")),
        },
    }


def render_lua(theme: dict) -> str:
    """Render theme dict as a Lua return statement."""
    cc = theme["custom_colors"]
    st = theme["status"]
    tb = theme["tab_bar"]
    tr = theme["terminal"]

    def arr(cols):
        return ", ".join(f'"{c}"' for c in cols)

    return f'''-- Generated by ~/.config/caelestia/scripts/wezterm-theme.py
-- DO NOT EDIT — regenerated on every wallpaper/theme change.
return {{
\tcustom_colors = {{
\t\tred     = "{cc['red']}",
\t\tcyan    = "{cc['cyan']}",
\t\tmagenta = "{cc['magenta']}",
\t\tyellow  = "{cc['yellow']}",
\t\tgreen   = "{cc['green']}",
\t}},

\tstatus = {{
\t\tworkspace  = "{st['workspace']}",
\t\tmode       = "{st['mode']}",
\t\tleader     = "{st['leader']}",
\t\tleader_fg  = "{st['leader_fg']}",
\t\tcwd        = "{st['cwd']}",
\t\tprocess    = "{st['process']}",
\t\tclock      = "{st['clock']}",
\t\tbattery    = "{st['battery']}",
\t}},

\ttab_bar = {{
\t\tbg        = "{tb['bg']}",
\t\tfg        = "{tb['fg']}",
\t\tgray      = "{tb['gray']}",
\t\tactive_bg = "{tb['active_bg']}",
\t\tactive_fg = "{tb['active_fg']}",
\t\tdefault_bg  = "{tb['default_bg']}",
\t\tdefault_fg  = "{tb['default_fg']}",
\t\thover_bg    = "{tb['hover_bg']}",
\t\thover_fg    = "{tb['hover_fg']}",
\t\tactive_bg2  = "{tb['active_bg2']}",
\t\tactive_fg2  = "{tb['active_fg2']}",
\t\tunseen      = "{tb['unseen']}",
\t\tprogress_ok = "{tb['progress_ok']}",
\t\tprogress_err = "{tb['progress_err']}",
\t\tprogress_ind = "{tb['progress_ind']}",
\t}},

\tterminal = {{
\t\tansi          = {{ {arr(tr['ansi'])} }},
\t\tbrights       = {{ {arr(tr['brights'])} }},
\t\tbackground    = "{tr['background']}",
\t\tforeground    = "{tr['foreground']}",
\t\tcursor_bg     = "{tr['cursor_bg']}",
\t\tcursor_fg     = "{tr['cursor_fg']}",
\t\tcursor_border = "{tr['cursor_border']}",
\t\tselection_bg  = "{tr['selection_bg']}",
\t\tselection_fg  = "{tr['selection_fg']}",
\t}},
}}
'''


def main():
    if not SCHEME_PATH.exists():
        print(f"Scheme file not found: {SCHEME_PATH}", file=sys.stderr)
        sys.exit(1)

    with open(SCHEME_PATH) as f:
        scheme = json.load(f)

    colours = scheme.get("colours", {})
    mode = scheme.get("mode", "dark")

    theme = build_theme(colours, mode)
    lua = render_lua(theme)

    THEME_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(THEME_PATH, "w") as f:
        f.write(lua)

    print(f"WezTerm theme written to {THEME_PATH} (mode={mode})")


if __name__ == "__main__":
    main()
