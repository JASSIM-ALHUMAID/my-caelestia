#!/usr/bin/env python3
"""Generate GTK/libadwaita theming from Caelestia scheme.json.

Reads ~/.local/state/caelestia/scheme.json, renders
~/.config/caelestia/gtk/{palette,nautilus}.css ({{ $name }} colour
placeholders) and writes the result into ~/.config/gtk-3.0 and
~/.config/gtk-4.0. Invoked by the caelestia cli.json postHook on every
wallpaper/theme change.

postHook runs last in the CLI's apply_colours(), after its own apply_gtk(),
so this script deliberately gets the final word on gtk.css and on the dconf
interface keys. It fixes three things apply_gtk() gets wrong:

  * its templates/gtk.css ends with `theme_selected_fg_color @primary`, and
    @primary is never defined, so GTK discards the declaration
  * it hardcodes gtk-theme to adw-gtk3-dark regardless of mode, so a light
    scheme keeps a dark shell theme
  * it writes icon-theme to dconf but never to settings.ini, so GTK4 apps and
    GTK3 apps disagree about icons

thunar.css is left alone — the CLI writes it, and palette.css imports it.
"""

import configparser
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

SCHEME_PATH = Path.home() / ".local/state/caelestia/scheme.json"
TEMPLATE_DIR = Path(__file__).parent.parent / "gtk"
GTK_DIRS = (
    Path.home() / ".config/gtk-3.0",
    Path.home() / ".config/gtk-4.0",
)

HEADER = (
    "/* Generated by gtk-theme.py from {name}\n"
    " * DO NOT EDIT — regenerated on every wallpaper/theme change. */\n\n"
)

# {{ $name }} — caelestia's own template convention. Literal, one space each
# side, matching the CLI's gen_replace() so the templates stay interchangeable.
PLACEHOLDER = re.compile(r"\{\{ \$(\w+) \}\}")

GS_SCHEMA = "/org/gnome/desktop/interface"


def hex_color(raw: str) -> str:
    """Ensure colour is #rrggbb format."""
    raw = raw.strip().lstrip("#")
    return f"#{raw[:6]}"


def atomic_write(path: Path, content: str) -> None:
    """Write via tempfile + rename.

    GTK watches these files and reloads on change; a non-atomic write can be
    read half-finished, which shows up as a flash of unstyled application.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    f = tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False)
    try:
        with f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        os.replace(f.name, path)
    except BaseException:
        os.unlink(f.name)
        raise


def render(template: Path, colours: dict) -> str:
    """Substitute every {{ $name }} placeholder, erroring on unknown names."""
    text = template.read_text()

    missing = {m for m in PLACEHOLDER.findall(text) if m not in colours}
    if missing:
        print(
            f"Colours missing from scheme for {template.name}: "
            f"{', '.join(sorted(missing))}",
            file=sys.stderr,
        )
        sys.exit(1)

    rendered = PLACEHOLDER.sub(lambda m: hex_color(colours[m.group(1)]), text)
    return HEADER.format(name=template.name) + rendered


def apply_dconf(mode: str) -> None:
    """Correct the interface keys apply_gtk() just wrote.

    icon-theme is left as the CLI set it: its default is already
    Papirus-Dark/Papirus-Light, both of which are installed.
    """
    theme = "adw-gtk3-dark" if mode == "dark" else "adw-gtk3"
    for key, value in (
        ("gtk-theme", theme),
        ("color-scheme", f"prefer-{mode}"),
    ):
        subprocess.run(
            ["dconf", "write", f"{GS_SCHEMA}/{key}", f"'{value}'"],
            stderr=subprocess.DEVNULL,
        )


def icon_theme_name(mode: str) -> str:
    return f"Papirus-{mode.capitalize()}"


def apply_settings_ini(mode: str) -> None:
    """Bring settings.ini in line with mode and with dconf.

    Only the three theme keys are touched — these files also carry the user's
    font, cursor and xft settings (nwg-look's), which must survive untouched.
    """
    updates = {
        "gtk-theme-name": "adw-gtk3-dark" if mode == "dark" else "adw-gtk3",
        "gtk-icon-theme-name": icon_theme_name(mode),
        "gtk-application-prefer-dark-theme": "1" if mode == "dark" else "0",
    }

    for gtk_dir in GTK_DIRS:
        path = gtk_dir / "settings.ini"
        parser = configparser.ConfigParser(interpolation=None)
        parser.optionxform = str  # GTK keys are case-sensitive
        if path.exists():
            parser.read(path)
        if not parser.has_section("Settings"):
            parser.add_section("Settings")

        for key, value in updates.items():
            parser.set("Settings", key, value)

        buf = []

        class _Sink:
            def write(self, s):
                buf.append(s)

        # space_around_delimiters=False keeps the `key=value` form GTK writes.
        parser.write(_Sink(), space_around_delimiters=False)
        atomic_write(path, "".join(buf))


def main():
    if not SCHEME_PATH.exists():
        print(f"File not found: {SCHEME_PATH}", file=sys.stderr)
        sys.exit(1)

    scheme = json.loads(SCHEME_PATH.read_text())
    colours = scheme.get("colours", {})
    mode = scheme.get("mode", "dark")

    outputs = {}
    for name, out_name in (("palette.css", "gtk.css"), ("nautilus.css", "nautilus.css")):
        template = TEMPLATE_DIR / name
        if not template.exists():
            print(f"File not found: {template}", file=sys.stderr)
            sys.exit(1)
        outputs[out_name] = render(template, colours)

    # nautilus.css goes into both dirs even though Nautilus is GTK4-only:
    # gtk.css is byte-identical in both, and its @import would otherwise
    # dangle under GTK3.
    for gtk_dir in GTK_DIRS:
        for out_name, content in outputs.items():
            atomic_write(gtk_dir / out_name, content)

    apply_dconf(mode)
    apply_settings_ini(mode)

    print(f"GTK theme updated ({mode}): {', '.join(str(d) for d in GTK_DIRS)}")


if __name__ == "__main__":
    main()
