#!/usr/bin/env python3
"""Generate dynamic starship config from Caelestia scheme.json.

Reads ~/.local/state/caelestia/scheme.json, renders
~/.config/caelestia/starship.toml.template ({name} colour placeholders)
and writes the result to ~/starship.toml (symlinked from
~/.config/starship.toml). Invoked by the caelestia cli.json postHook
on every wallpaper/theme change.
"""

import json
import sys
from pathlib import Path

SCHEME_PATH = Path.home() / ".local/state/caelestia/scheme.json"
TEMPLATE_PATH = Path(__file__).parent.parent / "starship.toml.template"
OUTPUT_PATH = Path.home() / "starship.toml"

HEADER = (
    "# Generated by starship-theme.py from starship.toml.template\n"
    "# DO NOT EDIT — regenerated on every wallpaper/theme change.\n\n"
)

COLOUR_KEYS = (
    "primary",
    "onPrimary",
    "secondary",
    "onSecondary",
    "tertiary",
    "onTertiary",
    "surfaceContainer",
    "error",
)


def hex_color(raw: str) -> str:
    """Ensure colour is #rrggbb format."""
    raw = raw.strip().lstrip("#")
    return f"#{raw[:6]}"


def main():
    for path in (SCHEME_PATH, TEMPLATE_PATH):
        if not path.exists():
            print(f"File not found: {path}", file=sys.stderr)
            sys.exit(1)

    with open(SCHEME_PATH) as f:
        colours = json.load(f).get("colours", {})

    result = TEMPLATE_PATH.read_text()
    for key in COLOUR_KEYS:
        if key not in colours:
            print(f"Colour missing from scheme: {key}", file=sys.stderr)
            sys.exit(1)
        result = result.replace(f"{{{key}}}", hex_color(colours[key]))

    OUTPUT_PATH.write_text(HEADER + result)
    print(f"Starship config updated: {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
